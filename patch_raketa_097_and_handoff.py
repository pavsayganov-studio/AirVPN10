def die(msg):
    print(f"\n\033[0;31m✗ {msg}\033[0m")
    sys.exit(1)

def ok(msg):
    print(f"\033[0;32m✓ {msg}\033[0m")

def info(msg):
    print(f"\033[1;33m→ {msg}\033[0m")

def main():
    if not os.path.exists(REPO_MARKER):
        die(f"Run this from the repo root (where {REPO_MARKER} lives).")

    print("\033[0;36m╔══════════════════════════════════════════╗")
    print("║   Raketa v0.9.7 — Python patch runner    ║")
    print("╚══════════════════════════════════════════╝\033[0m\n")

    # ── Step 1: apply the v0.9.7 bash patch verbatim ─────────────────────────
    # Decoded from base64 and executed via bash — byte-identical to the
    # version that already compiled and ran successfully, zero drift risk.
    info("Applying v0.9.7 patch (ViewController.m, Info.plist, build.yml)...")
    bash_script = base64.b64decode(BASH_PATCH_B64).decode("utf-8")
    proc = subprocess.run(["bash", "-c", bash_script])
    if proc.returncode != 0:
        die("Bash patch failed — see output above.")
    ok("v0.9.7 patch applied")

    # ── Step 2: write handoff.md ──────────────────────────────────────────────
    info("Writing handoff.md...")
    handoff_text = base64.b64decode(HANDOFF_B64).decode("utf-8")
    with open("handoff.md", "w", encoding="utf-8") as f:
        f.write(handoff_text)
    ok(f"handoff.md written ({len(handoff_text)} chars)")

    # ── Step 3: diagnose the git ref collision (informational only) ──────────
    info("Checking for a stray git tag literally named 'main'...")
    tag_check = subprocess.run(
        ["git", "tag", "-l", "main"], capture_output=True, text=True
    )
    stray_tag_exists = tag_check.stdout.strip() == "main"
    if stray_tag_exists:
        print("\033[0;31m  ⚠ Found a tag named \'main\' locally — this is what causes\033[0m")
        print("\033[0;31m    \'src refspec main matches more than one\' on push.\033[0m")
    else:
        ok("No stray local tag named 'main' (the explicit-refspec push below")
        print("    works regardless of where the collision actually lives).")

    # ── Final instructions ────────────────────────────────────────────────────
    print("\n\033[0;36m╔══════════════════════════════════════════════════════╗")
    print("║  Next steps — run these commands:                    ║")
    print("╠══════════════════════════════════════════════════════╣")
    print("║  git add -A                                          ║")
    print('║  git commit -m "v0.9.7: fix refresh icon + overlap;" ║')
    print('║      -m "add handoff.md"                             ║')
    print("║  git tag v0.9.7                                      ║")
    print("║                                                       ║")
    print("║  # Explicit refspec sidesteps the 'main' ambiguity:  ║")
    print("║  git push origin refs/heads/main:refs/heads/main     ║")
    print("║  git push origin v0.9.7                              ║")
    print("╚══════════════════════════════════════════════════════╝\033[0m")

    if stray_tag_exists:
        print("\n\033[1;33mOptional one-time cleanup (only if nothing else uses it):\033[0m")
        print("  git tag -d main")
        print("  git push origin :refs/tags/main")

if __name__ == "__main__":
    main()
